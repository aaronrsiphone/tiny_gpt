# coding: utf-8
'''
Regenerate tinygpt/hf/unicode_tables.py from the reference tokenizer.

The byte-level BPE pre-tokenizer used by GPT-2-style Hugging Face
tokenizers splits text with the regex classes \\p{L}, \\p{N} and \\s, and
its Digits step isolates every char for which Rust's char::is_numeric()
is true. Python's re module has none of those classes, and Python's own
unicodedata lags the Unicode version the Rust library is built with
(Pythonista's Python lags further). So the classes are measured here,
codepoint by codepoint, from the `tokenizers` library itself and frozen
into a table: tokenization then cannot drift with the Python version.

Needs `pip install tokenizers` on a desktop. Takes ~15 s.

    python tools/gen_unicode_tables.py
'''

import os
import sys


def ranges(flags):
    out = []
    start = None
    for cp, f in enumerate(flags):
        if f and start is None:
            start = cp
        elif not f and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, len(flags) - 1))
    return out


def measure():
    import tokenizers
    from tokenizers import pre_tokenizers as P
    bl = P.ByteLevel(add_prefix_space=False, use_regex=True)
    dg = P.Digits(individual_digits=True)
    n = 0x110000
    L, N, W, D = ([False] * n for _ in range(4))
    for cp in range(n):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        # 'a'+c is one regex piece iff c is a letter, '1'+c iff a number,
        # '!'+c iff neither and not whitespace. What is left is \\s.
        L[cp] = len(bl.pre_tokenize_str('a' + c)) == 1
        N[cp] = len(bl.pre_tokenize_str('1' + c)) == 1
        other = len(bl.pre_tokenize_str('!' + c)) == 1
        W[cp] = not (L[cp] or N[cp] or other)
        D[cp] = len(dg.pre_tokenize_str('a' + c + 'a')) == 3
    return tokenizers.__version__, L, N, W, D


def main():
    ver, L, N, W, D = measure()
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        '..', 'tinygpt', 'hf', 'unicode_tables.py')
    tables = (('LETTER', L, 'regex \\p{L}'),
              ('NUMBER', N, 'regex \\p{N}'),
              ('WHITE_SPACE', W, 'regex \\s'),
              ('NUMERIC', D, "Rust char::is_numeric (Digits)"))
    with open(path, 'w') as f:
        f.write('# coding: utf-8\n# Generated by tools/gen_unicode_tables'
                '.py, measured from tokenizers %s. Do not edit.\n' % ver)
        f.write('TOKENIZERS_VERSION = %r\n\n' % ver)
        for name, flags, what in tables:
            rs = ranges(flags)
            f.write('# %s\n%s = (\n' % (what, name))
            for i in range(0, len(rs), 4):
                f.write('    ' + ' '.join('(0x%X, 0x%X),' % r
                                          for r in rs[i:i + 4]) + '\n')
            f.write(')\n\n')
            print('%-12s %4d ranges' % (name, len(rs)))
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    sys.exit(main())
